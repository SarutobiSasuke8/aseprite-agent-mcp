"""Regenerate docs/TOOLS.md from the supported entry point's full tool surface.

Usage: uv run python scripts/generate_tools_doc.py [--check]

--check exits non-zero when the committed file is out of date (for CI or pre-release).
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

from aseprite_mcp.agent_server import CORE, ENV_VAR, configure, tool_groups

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "TOOLS.md"


def render() -> str:
    from aseprite_mcp.agent_server import mcp

    configure("all")
    tools = sorted(asyncio.run(mcp.list_tools()), key=lambda t: t.name)
    groups = tool_groups()
    group_of = {name: g for g, names in groups.items() if g not in ("all", "core") for name in names}
    lines = [
        "# Tool reference",
        "",
        "Generated by `scripts/generate_tools_doc.py` from the supported entry point. Frames are 1-based;",
        "coordinates are pixels from the top-left. Do not edit by hand.",
        "",
        f"The exposed surface is chosen with `{ENV_VAR}` (default `core`). {len(tools)} tools exist in",
        f"the `all` profile; {len(CORE)} are in `core` (marked **core** below).",
        "",
        "| Group | Tools |",
        "| --- | --- |",
        f"| core | {', '.join(sorted(CORE))} |",
    ]
    for g in sorted(k for k in groups if k not in ("all", "core")):
        lines.append(f"| {g} | {', '.join(sorted(groups[g]))} |")
    lines.append("")
    for t in tools:
        tag = " (**core**)" if t.name in CORE else ""
        lines += [f"## {t.name}{tag}", "", f"Group: `{group_of.get(t.name, '?')}`", "",
                  (t.description or "").strip(), "", "```json",
                  json.dumps(t.inputSchema, indent=2), "```", ""]
    configure(None)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("docs/TOOLS.md is out of date; run scripts/generate_tools_doc.py")
            return 1
        print("docs/TOOLS.md is current")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
